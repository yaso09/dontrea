#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync, execSync } = require('node:child_process');
const { gzipSync } = require('node:zlib');

const root = path.resolve(__dirname, '..');
const browserBundle = path.join(root, 'node_modules', 'javascript-obfuscator', 'dist', 'index.browser.js');
const license = path.join(root, 'node_modules', 'javascript-obfuscator', 'dist', 'index.browser.js.LICENSE.txt');
const sharedCore = path.join(root, 'lib', 'obfuscation-core.js');
const outputDir = path.join(root, 'www');
const outputFile = path.join(outputDir, 'dontrea-playground-wasm.js');
const wrapper = String.raw`
var self = globalThis;
`;
const core = String.raw`
function readRequest() {
    const decoder = new TextDecoder();
    const chunks = [];
    while (true) {
        const buffer = new Uint8Array(65536);
        const size = Javy.IO.readSync(0, buffer);
        if (!size) break;
        chunks.push(decoder.decode(buffer.subarray(0, size), { stream: true }));
    }
    chunks.push(decoder.decode());
    return JSON.parse(chunks.join(''));
}

function writeResponse(value) {
    Javy.IO.writeSync(1, new TextEncoder().encode(JSON.stringify(value)));
}

try {
    const request = readRequest();
    const options = request.options || {};
    const code = DontreaObfuscationCore.obfuscateDontreaCode(JavaScriptObfuscator, request.code, options);
    writeResponse({ ok: true, code });
} catch (error) {
    writeResponse({ ok: false, error: String(error && error.message || error) });
}
`;

if (!fs.existsSync(browserBundle)) {
  console.error('javascript-obfuscator browser bundle is missing. Run npm install first.');
  process.exit(1);
}
fs.mkdirSync(outputDir, { recursive: true });
const buildRoot = path.join(root, 'wasm');
fs.mkdirSync(buildRoot, { recursive: true });
const tempDir = fs.mkdtempSync(path.join(buildRoot, '.playground-build-'));
try {
  const sourceFile = path.join(tempDir, 'playground-core.js');
  const wasmFile = path.join(tempDir, 'playground-core.wasm');
  fs.writeFileSync(sourceFile, `${wrapper}\n${fs.readFileSync(browserBundle, 'utf8')}\n${fs.readFileSync(sharedCore, 'utf8')}\n${core}`, 'utf8');
  if (process.platform === 'win32') {
    execSync(`javy compile "${sourceFile}" -o "${wasmFile}"`, { stdio: 'inherit', shell: 'powershell.exe' });
  } else {
    execFileSync('javy', ['compile', sourceFile, '-o', wasmFile], { stdio: 'inherit' });
  }
  const encoded = gzipSync(fs.readFileSync(wasmFile), { level: 9 }).toString('base64');
  fs.writeFileSync(outputFile, `/* Generated by npm run build:playground-wasm. */\nwindow.DONTREA_PLAYGROUND_WASM_GZIP_BASE64 = '${encoded}';\n`, 'utf8');
  if (fs.existsSync(license)) {
    fs.writeFileSync(path.join(outputDir, 'THIRD-PARTY-NOTICES.txt'), fs.readFileSync(license));
  }
  console.log(`Playground Wasm bundle created: ${path.relative(root, outputFile)}`);
} finally {
  fs.rmSync(tempDir, { recursive: true, force: true });
}
